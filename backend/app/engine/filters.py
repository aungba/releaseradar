"""Stage 1: drop files that carry no deployable logic.

Rules are data so a per-project override (``.releaseradar.yml``, Phase 2) can extend them.
"""

from collections.abc import Iterable, Sequence

from app.engine.globs import match_any
from app.engine.models import SkippedFile, SkipReason
from app.integrations.git.base import FileDiff

LOCKFILES = (
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb",
    "poetry.lock", "uv.lock", "Pipfile.lock", "pdm.lock", "Gemfile.lock", "composer.lock",
    "Cargo.lock", "go.sum", "packages.lock.json", "mix.lock", "pubspec.lock", "Podfile.lock",
)  # fmt: skip
BUILD_OUTPUT = (
    "dist/**", "**/dist/**", "build/**", "target/**", "out/**", ".next/**", "**/.next/**",
    "coverage/**", "*.min.js", "*.min.css", "*.map", "*.pyc",
)  # fmt: skip
MEDIA = (
    "*.svg", "*.png", "*.jpg", "*.jpeg", "*.gif", "*.webp", "*.ico", "*.bmp", "*.tiff",
    "*.woff", "*.woff2", "*.ttf", "*.otf", "*.eot", "*.mp3", "*.mp4", "*.mov", "*.webm",
    "*.pdf", "*.zip", "*.gz", "*.tar", "*.jar",
)  # fmt: skip
VENDORED = (
    "vendor/**",
    "**/vendor/**",
    "**/node_modules/**",
    "third_party/**",
    "**/third_party/**",
)
GENERATED = (
    "*_pb2.py", "*_pb2_grpc.py", "*.pb.go", "*.pb.ts", "*.generated.*", "*.g.dart",
    "**/__snapshots__/**", "*.snap",
)  # fmt: skip

NOISE_PATTERNS: tuple[str, ...] = LOCKFILES + BUILD_OUTPUT + MEDIA + VENDORED + GENERATED

_GENERATED_MARKERS = ("@generated", "do not edit", "code generated by")
_MARKER_SCAN_LINES = 12


def has_generated_marker(patch: str | None) -> bool:
    if not patch:
        return False
    head = patch.splitlines()[1 : _MARKER_SCAN_LINES + 1]
    return any(marker in line.lower() for line in head for marker in _GENERATED_MARKERS)


def skip_reason(file: FileDiff, patterns: Iterable[str] = NOISE_PATTERNS) -> SkipReason | None:
    """Why this file should not be analyzed, or None to keep it."""
    if match_any(file.path, patterns) or has_generated_marker(file.patch):
        return SkipReason.NOISE
    if file.is_binary:
        return SkipReason.BINARY
    return None


def partition(
    files: Sequence[FileDiff], patterns: Iterable[str] = NOISE_PATTERNS
) -> tuple[list[FileDiff], list[SkippedFile]]:
    """Split into (kept, skipped). ``PATCH_OMITTED`` files are kept: they are not noise."""
    kept: list[FileDiff] = []
    skipped: list[SkippedFile] = []
    patterns = tuple(patterns)
    for file in files:
        reason = skip_reason(file, patterns)
        if reason is None:
            kept.append(file)
        else:
            skipped.append(SkippedFile(path=file.path, reason=reason))
    return kept, skipped
