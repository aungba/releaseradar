def test_generated_marker_is_noise() -> None:
    patch = added("// Code generated by protoc-gen-go. DO NOT EDIT.", "package api")
    assert skip_reason(fd("api/types.go", patch)) is SkipReason.NOISE


def test_binary_is_skipped_but_omitted_patch_is_kept() -> None:
    kept, skipped = partition(
        [
            fd("data/model.bin", None, is_binary=True),
            fd("src/big.py", None, patch_omitted=True),
            fd("yarn.lock"),
        ]
    )
    assert [f.path for f in kept] == ["src/big.py"]
    assert {(s.path, s.reason) for s in skipped} == {
        ("data/model.bin", SkipReason.BINARY),
        ("yarn.lock", SkipReason.NOISE),
    }


# ---------------------------------------------------------------- redaction


def test_redacts_known_token_formats() -> None:
    patch = added(
        'aws = "AKIA' + "ABCDEFGHIJKLMNOP" + '"',
        'gh = "ghp_' + "a" * 36 + '"',
        'stripe = "sk_' + "live_" + "b" * 24 + '"',
        "url = 'postgres://admin:hunter2@db:5432/app'",
    )
    redacted, count = redact_patch("src/config.py", patch)
    assert count == 4
    assert "AKIA" not in redacted and "ghp_" not in redacted and "sk_live" not in redacted
    assert "hunter2" not in redacted and "postgres://«redacted»@db" in redacted


def test_redacts_config_values_but_keeps_names() -> None:
    patch = added(
        "STRIPE_SECRET_KEY=sk_abc123", "DATABASE_PASSWORD=hunter2", "API_TOKEN=", "DEBUG=true"
    )
    redacted, count = redact_patch(".env.production", patch)
    assert f"+STRIPE_SECRET_KEY={MASK}" in redacted
    assert f"+DATABASE_PASSWORD={MASK}" in redacted
    assert "+API_TOKEN=\n" in redacted  # empty value untouched
    assert "+DEBUG=true" in redacted
    assert count == 2


@pytest.mark.parametrize(
    "value", ["${STRIPE_KEY}", "changeme", "<your-key>", '""', "your-key-here"]
)
def test_placeholders_are_not_redacted(value: str) -> None:
    redacted, count = redact_patch("config.yaml", added(f"stripe_key: {value}"))
    assert count == 0
    assert value in redacted


def test_keyword_must_be_a_whole_name_segment() -> None:
    redacted, count = redact_patch("config.yaml", added("keycloak_url: https://sso", "monkey: 1"))
    assert count == 0


def test_code_assignments_are_not_treated_as_config() -> None:
    line = 'API_KEY = os.getenv("API_KEY")'
    redacted, _ = redact_patch("src/settings.py", added(line))
    assert line in redacted


def test_private_key_block_is_masked() -> None:
    patch = added(
        "-----BEGIN RSA PRIVATE KEY-----",
        "MIIEowIBAAKCAQEA",
        "abcdef",
        "-----END RSA PRIVATE KEY-----",
    )
    redacted, count = redact_patch("deploy/key.pem", patch)
    assert "MIIEowIBAAKCAQEA" not in redacted and "abcdef" not in redacted
    assert "-----BEGIN RSA PRIVATE KEY-----" in redacted
    assert count == 2


def test_high_entropy_strings_masked_but_shas_kept() -> None:
    secret = "Zx8qL2mN7vB4cR9tY1wE6uI3oP5aS0dF"
    sha = "3f786850e387550fdab836ed7e6dc881de23001b"
    redacted, count = redact_patch("src/app.py", added(f'token = "{secret}"', f'rev = "{sha}"'))
    assert secret not in redacted
    assert sha in redacted
    assert count == 1


