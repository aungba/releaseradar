@pytest.mark.parametrize(
    ("path", "tier"),
    [
        ("alembic/versions/0002_drop.py", Tier.CRITICAL),
        ("db/migrations/20260101_add.sql", Tier.CRITICAL),
        ("api/openapi.yaml", Tier.CRITICAL),
        ("proto/payments.proto", Tier.CRITICAL),
        ("app/routers/payments.py", Tier.CRITICAL),
        (".env.example", Tier.CRITICAL),
        ("Dockerfile", Tier.CRITICAL),
        ("deploy/helm/values.yaml", Tier.CRITICAL),
        ("package.json", Tier.CRITICAL),
        ("requirements-prod.txt", Tier.CRITICAL),
        ("app/auth/jwt.py", Tier.CRITICAL),
        ("app/services/billing.py", Tier.CORE),
        ("src/utils/money.ts", Tier.CORE),
        ("tests/test_billing.py", Tier.LOW),
        ("src/billing.test.ts", Tier.LOW),
        ("tests/migrations/test_0002.py", Tier.LOW),
        ("docs/runbook.md", Tier.LOW),
        ("web/src/app.scss", Tier.LOW),
    ],
)
def test_path_tier(path: str, tier: Tier) -> None:
    assert path_tier(path) is tier


def test_promotion_only_for_core_files_with_strong_signals() -> None:
    env = (Signal(kind=SignalKind.ENV_VAR_ADDED, file_path="x.py", symbol="X"),)
    dep = (Signal(kind=SignalKind.DEPENDENCY_CHANGED, file_path="x.py", symbol="y"),)
    assert promote(Tier.CORE, env) is Tier.CRITICAL
    assert promote(Tier.CORE, dep) is Tier.CORE
    assert promote(Tier.LOW, env) is Tier.LOW
    assert promote(Tier.CORE, ()) is Tier.CORE


def test_fd_helper_status_default() -> None:
    assert fd("x.py").status is ChangeType.MODIFIED
